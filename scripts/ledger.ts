/**
 * Writes docs/human-input.md from app/content/human.ts: every statement a
 * person made that shaped the plans, and where each landed on the site.
 * `bun run ledger` after editing human.ts; a unit test fails if it's stale.
 */

import { writeFile } from "node:fs/promises";
import { HUMAN, HUMAN_IDS, type Said } from "../app/content/human";
import { REVIEW_ITEMS, type ReviewItem } from "../app/content/review";

export const LEDGER_FILE = "docs/human-input.md";

const KIND: Record<Said["kind"], string> = {
  said: "said",
  approved: "approved the AI's proposal",
  answered: "answered",
};

export function ledgerMarkdown(): string {
  const used = new Map<string, ReviewItem[]>();
  for (const item of REVIEW_ITEMS) {
    for (const id of [...(item.credit?.h ?? []), ...(item.conflict?.h ?? [])]) {
      used.set(id, [...(used.get(id) ?? []), item]);
    }
  }
  const lines = [
    "# What people said",
    "",
    "<!-- Generated by `bun run ledger` from app/content/human.ts. Don't edit by hand. -->",
    "",
    "Every statement from the planning conversations (2026-10-19 to 2026-10-23)",
    "that shaped these plans. **Anything in the plans or on the site not traced",
    "to an entry here is an AI draft**: a guess or design choice nobody has",
    "checked yet. The site marks each block either way; `/review` walks through",
    "the AI drafts.",
    "",
    "In `plans/`, 🧑 H12 marks a person's statement (this ledger's id) and 🤖",
    "marks the AI's own call. Times are US Pacific.",
    "",
    "⚠ marks where the AI read more into a statement than was said. Check those.",
    "",
  ];
  for (const id of HUMAN_IDS) {
    const h: Said = HUMAN[id];
    lines.push(`## ${id}: ${h.meaning}`, "");
    lines.push(
      `${h.who} ${KIND[h.kind]}, ${h.at} (${h.thread === "empyrean" ? "Empyrean repo chat" : "this repo's chat"}):`,
      "",
    );
    lines.push(`> ${h.said}`, "");
    if (h.aiReading) lines.push(`⚠ AI's reading: ${h.aiReading}`, "");
    if (h.supersededBy) lines.push(`Replaced by ${h.supersededBy}.`, "");
    const items = used.get(id) ?? [];
    if (items.length) {
      lines.push(
        `On the site: ${items.map((i) => `${i.title}${i.conflict?.h.includes(id as never) ? " (≠ the AI differs)" : ""}`).join("; ")}.`,
        "",
      );
    }
  }
  return lines.join("\n").replace(/\n+$/, "\n");
}

if (import.meta.main) {
  await writeFile(LEDGER_FILE, ledgerMarkdown(), "utf8");
  console.log(`Wrote ${LEDGER_FILE} (${HUMAN_IDS.length} entries).`);
}
